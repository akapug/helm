SCHEMA = 1
# GIT SELECTION ENV OVERRIDES `-C`, WHICH MAKES EVERY `git -C <path>` HERE A
# REQUEST RATHER THAN AN INSTRUCTION. Measured: with GIT_DIR and GIT_WORK_TREE
# pointing at repository B, `git -C A rev-parse --show-toplevel` answers B. So
# `--project A` would resolve its artifact root inside B and ask B whether the
# path is ignored — the project-local runtime would bind the WRONG repository,
# defeating the one invariant the mode exists to hold, with no flag involved.
# This mirrors `dispatches._GIT_SELECTION_ENV` deliberately rather than
# importing it: this file must keep working when the mutable package does not
# import, so the list is duplicated and must be kept in step with that one.
_GIT_SELECTION_ENV = ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE",
                      "GIT_COMMON_DIR", "GIT_OBJECT_DIRECTORY",
                      "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_NAMESPACE",
                      "GIT_CEILING_DIRECTORIES")


def _git_env():
    """The environment with Git's repository-SELECTION variables removed."""
    return {k: v for k, v in os.environ.items()
            if k not in _GIT_SELECTION_ENV}


MANIFEST = "artifact-manifest.json"
REQUIRED_FILES = (
    "bin/helm",
    "bin/helm-hook",
    "helm/__init__.py",
    "helm/cli.py",
    "README.md",
)
REQUIRED_TREES = ("docs/", "tests/")
# EVERY SHIPPED ENTRY POINT, NOT THE ONE SOMEONE REMEMBERED TO NAME. Both mode
# checks used to spell `bin/helm` inline, so the second entry point the tree
# grew — `bin/helm-hook`, which every generated hook command in every settings
# file now execs — was in no registry at all: an artifact that shipped it
# absent or mode 644 passed every deploy gate, and the whole fleet would then
# fail OPEN on every hook with nothing in helm's voice saying why (the wrapper
# cannot announce its own absence; the shell exits 127 first). A list both
# checks iterate makes the next entry point a one-line addition instead of a
# silent omission.
EXECUTABLE_FILES = ("bin/helm", "bin/helm-hook")

