# pi stamps PI_CODING_AGENT="true" at its own startup (cli.ts:13) —
# unconditionally, and before helm's launch line has even exec'd. helm does
# NOT prefix it here; pi's own config owns the marker.


def pi_binary():
    """The pi executable, or None. which(pi) — pi ships its own binary name."""
    import shutil
    return shutil.which("pi")


def _pi_api_key(seat, family=None):
    """The seat's proxy API key (the api-keys stanza from its 0600
    config.yaml), or None. ONE narrow read — no full-config load that could
    get logged. The key value is secret: callers must NEVER print, log, or
    return it through a surface that renders it."""
    from . import seat as seatmod
    if family is None:
        family, _err = seatmod._seat_family(seat)
    if not family:
        return None                # unresolvable seat — no config to read
    try:
        config_path = os.path.join(seatmod._proxy_home(family, seat),
                                   "config.yaml")
        # Scope to the api-keys stanza only: everything between
        # 'api-keys:' and the next non-indented line.
        in_keys = False
        with open(config_path) as f:
            for line in f:
                stripped = line.strip()
                if stripped == "api-keys:":
                    in_keys = True
                    continue
                if not in_keys:
                    continue
                # a non-indented line after api-keys: — end of stanza
                if stripped and not line.startswith((" ", "\t")):
                    break
                if stripped.startswith("- "):
                    return stripped[2:].strip().strip('"')
    except (OSError, ValueError):
        pass
    return None


def _proxy_descriptor(seat):
    """Canonical runtime + default Pi model for one helm proxy seat."""
    from . import seat as seatmod
    family, err = seatmod._seat_family(seat)
    if err:
        return None, err
    model = (seatmod.FAMILIES.get(family) or {}).get("model")
    if not model:
        return None, "family %s declares no model" % family
    return {"runtime": {"agent_harness": "pi", "family": family,
                        "backend": "proxy"},
            "seat": "pi-" + seat,
            "model": provider_name(seat) + "/" + model}, None


def _runtime_prefix(model):
    """Launch labels; clear axes the selected provider cannot prove."""
    env = ["env", "-u", "HELM_MODEL_FAMILY", "-u", "HELM_MODEL_BACKEND",
           "HELM_AGENT_HARNESS=pi"]
    provider = str(model or "").split("/", 1)[0]
    if provider.startswith("helm-") and len(provider) > len("helm-"):
        desc, err = _proxy_descriptor(provider[len("helm-"):])
        if not err:
            runtime = desc["runtime"]
            env.extend(("HELM_MODEL_FAMILY=" + runtime["family"],
                        "HELM_MODEL_BACKEND=" + runtime["backend"],
                        "HELM_CHAT_NAME=" + desc["seat"]))
    return env


def pi_launch_line(binary=None, model=None, session=None, resume=False,
                   continue_recent=False, session_dir=None, prompt=None):
    """The exact pi launch command, for helm to print. The launch line NEVER
    carries the proxy key — that is set ONLY in the child's environment by
    `pi_run()`, which execs pi directly.

    Flags mirror pi's CLI (packages/coding-agent/src/cli/args.ts):
      --model provider/id:thinking  model selection
      --session <uuid|path>         resume a specific session
      --resume                      interactive session picker
      --continue                    continue the most recent session
      --print, -p <prompt>          non-interactive: process prompt and exit
      --session-dir <path>          override the default session directory

    pi stamps PI_CODING_AGENT=true at its own startup (cli.ts:13) —
    helm does NOT prefix it; the env is pi's own launch-time contract.
    Returns the launch line as a string, or None when pi is not installed.
    """
    binary = binary or pi_binary()
    if not binary:
        return None
    cmd = [binary]
    if model:
        cmd.extend(["--model", model])
    if session_dir:
        cmd.extend(["--session-dir", session_dir])
    if session:
        cmd.extend(["--session", session])
    if resume:
        cmd.append("--resume")
    if continue_recent:
        cmd.append("--continue")
    if prompt:
        # --print is boolean (args.ts:140); prompt is a POSITIONAL argument.
        # Append the unquoted prompt VALUE — the final shlex.quote in the join
        # will quote it once, avoiding double-quoting.
        cmd.extend(["--print", prompt])
    return " ".join(shlex.quote(p) for p in _runtime_prefix(model) + cmd)


def pi_run(seat="codex", args=None):
    """Exec pi through one helm seat's proxy, with key + runtime labels in env.

    The selected model is pinned to that seat's generated provider: a key in the
    environment does not itself route pi through the proxy. The key remains a
    Python environ assignment, never a returned/printed string or argv value.
    """
    binary = pi_binary()
    if not binary:
        return 1
    desc, err = _proxy_descriptor(seat)
    if err:
        print("helm pi: " + err, file=sys.stderr)
        return 1
    args = list(args or [])
    selected = []
    for i, arg in enumerate(args):
        if arg == "--model":
            selected.append(args[i + 1] if i + 1 < len(args) else "")
        elif arg.startswith("--model="):
            selected.append(arg.split("=", 1)[1])
    if len(selected) > 1 or selected == [""]:
        print("helm pi run: pass at most one valued --model", file=sys.stderr)
        return 2
    provider = selected[0].split("/", 1)[0] if selected else ""
    expected = provider_name(seat)
    if provider and provider != expected:
        print("helm pi run: --model must use %s (got %s)"
              % (expected, provider), file=sys.stderr)
        return 2
    if not selected:
        args[:0] = ["--model", desc["model"]]
    key = _pi_api_key(seat, desc["runtime"]["family"])
    if not key:
        print("helm pi: no proxy key for %s — cannot authenticate" % seat,
              file=sys.stderr)
        return 1
    env = os.environ.copy()
    env["HELM_PI_PROXY_KEY"] = key
    env["HELM_AGENT_HARNESS"] = desc["runtime"]["agent_harness"]
    env["HELM_MODEL_FAMILY"] = desc["runtime"]["family"]
    env["HELM_MODEL_BACKEND"] = desc["runtime"]["backend"]
    env["HELM_CHAT_NAME"] = desc["seat"]
    from . import seats
    seats.write_roster(desc["seat"], cwd=os.getcwd(), runtime=desc["runtime"],
                       presence_beat=False)
    cmd = [binary] + args
    os.execvpe(binary, cmd, env)
